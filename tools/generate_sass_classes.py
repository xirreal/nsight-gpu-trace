"""Generate src/sass_classes.rs from an installed Nsight Graphics 2026.3.1.

Nsight's shader profiler classifies every SASS instruction into a pipe, family,
and operation (the instruction mix). ShaderProfilerPlugin.dll computes this in
one function per SM generation from a 13-bit opcode key. This script calls
those functions for every key and every SM version they accept and writes the
results as a Rust table.

The function addresses are specific to the checked plugin build, so the script
refuses any other file. Run it on Windows with a Python whose own directory
contains no Qt DLLs (for example the python.org installer), because the plugin
loads Qt from the Nsight directory:

    python tools/generate_sass_classes.py "C:/Program Files/NVIDIA Corporation/Nsight Graphics 2026.3.1/host/windows-desktop-nomad-x64" src/sass_classes.rs
"""

import argparse
import ctypes
import hashlib
import os
import sys

PLUGIN_SHA256 = "727f7861b7a22d0eadc5cabbc6dcfb4e9af84eff82932813e35768312b4e2732"
IMAGE_BASE = 0x180000000
# SM generation -> classification function (selected in 0x1800b6250).
FUNCTIONS = {7: 0x1800AF6F0, 8: 0x1800B2530, 10: 0x1800A9240, 12: 0x1800AC420}
# cudaSmVersion values accepted by those functions, in table column order.
SM_VERSIONS = [
    (7, 0x70005),
    (8, 0x80006),
    (8, 0x80007),
    (8, 0x80008),
    (8, 0x80009),
    (10, 0xB0000),
    (12, 0xC0000),
    (12, 0xC0001),
]
KEY_COUNT = 0x2000


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("nsight_host", help="Nsight host directory containing Plugins/ShaderProfilerPlugin.dll")
    parser.add_argument("output", help="Rust file to write")
    args = parser.parse_args()

    plugin = os.path.join(args.nsight_host, "Plugins", "ShaderProfilerPlugin.dll")
    digest = hashlib.sha256(open(plugin, "rb").read()).hexdigest()
    if digest != PLUGIN_SHA256:
        sys.exit(f"{plugin} has SHA-256 {digest}; the function addresses are only known for {PLUGIN_SHA256}")

    os.add_dll_directory(args.nsight_host)
    os.add_dll_directory(os.path.dirname(plugin))
    module = ctypes.WinDLL(plugin)
    signature = ctypes.CFUNCTYPE(ctypes.c_ulonglong, ctypes.c_int, ctypes.c_int, ctypes.c_void_p)
    functions = {gen: signature(module._handle + (va - IMAGE_BASE)) for gen, va in FUNCTIONS.items()}

    rows = {}
    for column, (generation, version) in enumerate(SM_VERSIONS):
        for key in range(KEY_COUNT):
            result = ctypes.create_string_buffer(16)
            if not functions[generation](key, version, result) & 0xFF:
                continue
            family, operation, pipe = result.raw[0], result.raw[1], result.raw[2]
            packed = family << 16 | operation << 8 | pipe
            # Nsight treats an all-zero class as "no category", like a missing key.
            if packed != 0:
                rows.setdefault(key, [0] * len(SM_VERSIONS))[column] = packed

    lines = [
        "//! SASS instruction classes generated by `tools/generate_sass_classes.py` from the",
        "//! instruction mix classification of Nsight Graphics 2026.3.1",
        f"//! (`ShaderProfilerPlugin.dll`, SHA-256 {PLUGIN_SHA256[:16]}...).",
        "",
        "/// `cudaSmVersion` values in the column order of [`CLASSES`].",
        f"pub(crate) const SM_VERSIONS: [u32; {len(SM_VERSIONS)}] = [",
        "    " + ", ".join(f"{version:#x}" for _, version in SM_VERSIONS) + ",",
        "];",
        "",
        "/// `(opcode key, [family << 16 | operation << 8 | pipe; SM_VERSIONS])`; 0 is unclassified.",
        "#[rustfmt::skip]",
        f"pub(crate) const CLASSES: &[(u16, [u32; {len(SM_VERSIONS)}])] = &[",
    ]
    for key in sorted(rows):
        values = ", ".join(f"{value:#08x}" for value in rows[key])
        lines.append(f"    ({key:#06x}, [{values}]),")
    lines += ["];", ""]
    with open(args.output, "w", encoding="utf-8", newline="\n") as output:
        output.write("\n".join(lines))
    print(f"{len(rows)} opcode keys for {len(SM_VERSIONS)} SM versions written to {args.output}")


if __name__ == "__main__":
    main()
