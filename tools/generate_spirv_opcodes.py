"""Generate src/spirv_opcodes.rs from the Khronos SPIR-V grammar.

The SPIR-V parser needs every opcode's name and whether the instruction has a
result type and a result id, so that it can describe the SPIR-V instruction a
PC sample falls on. This script reads `spirv.core.grammar.json` from the
Khronos SPIR-V Headers (`include/spirv/unified1/`, also shipped with the Vulkan
SDK) and writes those three facts as a Rust table:

    python tools/generate_spirv_opcodes.py "C:/VulkanSDK/1.4.363.0/Include/spirv/unified1/spirv.core.grammar.json" src/spirv_opcodes.rs
"""

import argparse
import json


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("grammar", help="path to spirv.core.grammar.json")
    parser.add_argument("output", help="Rust file to write")
    args = parser.parse_args()

    with open(args.grammar, encoding="utf-8") as grammar_file:
        grammar = json.load(grammar_file)
    opcodes = {}
    for instruction in grammar["instructions"]:
        opcode = instruction["opcode"]
        # Aliases repeat an opcode under a newer name; keep the first one.
        if opcode in opcodes:
            continue
        kinds = [operand["kind"] for operand in instruction.get("operands", [])]
        operands = (1 if "IdResultType" in kinds else 0) | (2 if "IdResult" in kinds else 0)
        opcodes[opcode] = (instruction["opname"], operands)

    version = f"{grammar['major_version']}.{grammar['minor_version']} revision {grammar['revision']}"
    lines = [
        "//! SPIR-V opcode names generated by `tools/generate_spirv_opcodes.py` from the",
        "//! Khronos SPIR-V Headers grammar (`spirv.core.grammar.json`, SPIR-V",
        f"//! {version}, MIT license).",
        "",
        "/// `(opcode, name, operands)`; operand bit 1 marks a result type, bit 2 a result id.",
        "#[rustfmt::skip]",
        "pub(crate) const OPCODES: &[(u16, &str, u8)] = &[",
    ]
    for opcode in sorted(opcodes):
        name, operands = opcodes[opcode]
        lines.append(f'    ({opcode}, "{name}", {operands}),')
    lines += ["];", ""]
    with open(args.output, "w", encoding="utf-8", newline="\n") as output:
        output.write("\n".join(lines))
    print(f"{len(opcodes)} opcodes of SPIR-V {version} written to {args.output}")


if __name__ == "__main__":
    main()
